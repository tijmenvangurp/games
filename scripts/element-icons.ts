/**
 * Which icon belongs to which Mengelmoes element. `scripts/build-element-sprites.ts`
 * turns this list into the committed SVG's in `apps/games/public/elements/`.
 *
 * A source is a list of Iconify references (`set:name`), highest priority first.
 * The first match wins, so an element can fall back to another set when Fluent
 * Emoji has no suitable sprite. Sets are plain dev dependencies:
 *
 *   pnpm add -D @iconify-json/<prefix>
 *
 * then reference `<prefix>:<name>`. The app never loads a set at runtime.
 *
 * Monochrome sets use `currentColor`; set `color` to give such an icon an ink
 * colour, otherwise it would render black inside an `<img>`.
 */
export type ElementIconSource =
  | { readonly icons: readonly string[]; readonly color?: string }
  | { readonly custom: true };

